public class Variable {
    public static void main(String[] args) {
        // 선언과 동시에 값 대입

        int number = 10; // 정수형
        float decimal = 3.14f; // 실수형
        String text = "문자열";  // 문자열
        char character = 'a';  // 문자
        boolean isBoolean = true;  // 논리형

        // 변수 선언 후 값을 대입하기
        int num;
        num = 17; 

        
        // 변수 값 출력
        System.out.println("정수형: " + number);
        System.out.println("실수형: " + decimal);
        System.out.println("문자열: " + text);
        System.out.println("문자: " + character);
        System.out.println("논리형: " + isBoolean);
    }
}
